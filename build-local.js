function between(startMarker, endMarker) {
  const a = src.findIndex((l) => l.indexOf(startMarker) === 0);
  const b = src.findIndex((l, i) => i > a && l.indexOf(endMarker) === 0);
  if (a < 0 || b < 0) throw new Error("marker nahi mila: " + startMarker + " / " + endMarker);
  return src.slice(a, b).join("\n");
}

